"""Apply reviewed copyedits to text runs in the original Word package."""
from difflib import SequenceMatcher
from pathlib import Path
import re
from zipfile import ZipFile

from lxml import etree

from common.helpers import write_json
from common.sample_policy import sample_count

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
XML_SPACE = "{http://www.w3.org/XML/1998/namespace}space"
STORY = re.compile(r"word/(?:document|header\d+|footer\d+|footnotes|endnotes)\.xml")
OUTPUTS = ["final/final.docx", "final/final.pdf", "final/sample.docx", "final/sample.pdf"]
BLOCKS = "extracted/editable_blocks.json"
EDITS = "planning/copyedits.json"
RENDER = "reports/editing_render.json"


def editable_stories(package):
    """Index text that can change without touching hyperlinks, fields or markup."""
    roots, blocks = {}, {}
    for name in sorted(package.namelist()):
        if not STORY.fullmatch(name):
            continue
        root = etree.fromstring(package.read(name), etree.XMLParser(resolve_entities=False, no_network=True))
        roots[name] = root
        field_depth = 0
        for number, paragraph in enumerate(root.iter(W + "p"), 1):
            if any(parent.tag in {W + "del", W + "ins", W + "moveFrom", W + "moveTo"}
                   for parent in paragraph.iterancestors()):
                continue
            # Field results (including bibliographies/TOCs) are generated by Word.
            fields = [c for run in paragraph for c in run if c.tag == W + "fldChar"]
            before_depth = field_depth
            for field in fields:
                action = field.get(W + "fldCharType")
                field_depth = max(0, field_depth + (action == "begin") - (action == "end"))
            if fields or before_depth:
                continue
            groups = [[]]
            for child in paragraph:
                if child.tag == W + "pPr":
                    continue
                if child.tag == W + "r":
                    for run_part in child:
                        if run_part.tag == W + "t":
                            groups[-1].append(run_part)
                        elif run_part.tag != W + "rPr" and groups[-1]:
                            groups.append([])
                elif groups[-1]:
                    groups.append([])
            for group, nodes in enumerate(groups, 1):
                if nodes and block_text(nodes).strip():
                    blocks[f"{name}:{number}:{group}"] = (name, nodes)
    return roots, blocks


def block_text(nodes):
    return "".join(node.text or "" for node in nodes)


def extract(source: Path, destination: Path):
    with ZipFile(source) as package:
        if "word/document.xml" not in package.namelist():
            raise ValueError("The source is not a Word DOCX document")
        _, blocks = editable_stories(package)
    if not blocks:
        raise ValueError("The Word source has no editable text paragraphs")
    result = [{"id": key, "text": block_text(nodes)} for key, (_, nodes) in blocks.items()]
    write_json(destination, {"blocks": result})
    return len(result)


def set_block_text(nodes, original, revised):
    # Retain the formatting of unchanged characters. New text takes the
    # formatting of the first affected character or its adjacent run.
    owners = [i for i, node in enumerate(nodes) for _ in node.text or ""]
    content = ["" for _ in nodes]
    for action, start, end, new_start, new_end in SequenceMatcher(None, original, revised, autojunk=False).get_opcodes():
        if action == "equal":
            for index in range(start, end):
                content[owners[index]] += original[index]
        elif action in {"replace", "insert"}:
            content[owners[min(start, len(owners) - 1)]] += revised[new_start:new_end]
    for node, text in zip(nodes, content):
        node.text = text
        if text != text.strip():
            node.set(XML_SPACE, "preserve")


def apply(source: Path, destination: Path, plan):
    if not isinstance(plan, dict) or not isinstance(plan.get("edits"), list) or not str(plan.get("summary") or "").strip():
        raise ValueError("The copyedit plan needs a summary and an edits array")
    with ZipFile(source) as package:
        roots, blocks = editable_stories(package)
        changed, seen = set(), set()
        for edit in plan["edits"]:
            if not isinstance(edit, dict) or not isinstance(edit.get("id"), str):
                raise ValueError("Every copyedit requires a block ID")
            identifier = edit["id"]
            if identifier in seen or identifier not in blocks:
                raise ValueError(f"Unknown or duplicate copyedit block: {identifier}")
            name, nodes = blocks[identifier]
            original, revised = block_text(nodes), edit.get("after")
            if edit.get("before") != original or not isinstance(revised, str) or not revised.strip():
                raise ValueError(f"The copyedit requires matching source text and a nonempty replacement: {identifier}")
            if revised == original or any(char in revised for char in "\r\n\t"):
                raise ValueError(f"The copyedit must change the text within its existing block: {identifier}")
            set_block_text(nodes, original, revised)
            changed.add(name)
            seen.add(identifier)
        if destination == source:
            raise ValueError("The source Word document is immutable")
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = destination.with_name(destination.stem + ".editing.tmp")
        try:
            with ZipFile(temporary, "w") as result:
                for item in package.infolist():
                    result.writestr(item, etree.tostring(roots[item.filename], xml_declaration=True, encoding="UTF-8")
                                    if item.filename in changed else package.read(item))
            temporary.replace(destination)
        finally:
            temporary.unlink(missing_ok=True)
    return len(seen)


def render(services):
    import fitz

    workspace = services.workspace
    final, pdf, excerpt, excerpt_pdf = [workspace / name for name in OUTPUTS]
    services.export_pdf(final, pdf, None)
    word_full, word_sample = services.create_sample(final, excerpt)
    services.export_pdf(excerpt, excerpt_pdf, None)
    images, counts = {}, {}
    for path in (pdf, excerpt_pdf):
        relative = path.relative_to(workspace).as_posix()
        with fitz.open(path) as document:
            counts[relative] = len(document)
            directory = workspace / "reports/rendered_pages" / path.stem
            directory.mkdir(parents=True, exist_ok=True)
            for index, page in enumerate(document, 1):
                image = directory / f"page-{index:04d}.png"
                page.get_pixmap(matrix=fitz.Matrix(1.5, 1.5)).save(image)
                images[image.relative_to(workspace).as_posix()] = {"pdf": relative, "page": index}
    if counts != {OUTPUTS[1]: word_full, OUTPUTS[3]: word_sample} or word_sample != sample_count(word_full):
        raise ValueError(f"Editing sample pagination differs from the 20% policy: {counts}")
    report = {"counts": counts, "images": images, "word_full_pages": word_full, "word_sample_pages": word_sample}
    write_json(workspace / RENDER, report)
    return report
